"""One small database layer: SQLite (a file path, the default for the CLI and tests) or
Postgres (a postgres:// URL, used when deployed, e.g. Neon), behind the same calls.

SQL in this repo is written once, in the common subset: "?" placeholders, ON CONFLICT
upserts, RETURNING. The only translations needed for Postgres are placeholders and the
auto-increment id column; table introspection for migrations is done by columns().
"""
from __future__ import annotations

import os
import sqlite3
from typing import Any, Iterable

AUTO_ID_SQLITE = "INTEGER PRIMARY KEY AUTOINCREMENT"
AUTO_ID_PG = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"


def is_postgres(target: str | None) -> bool:
    return bool(target) and target.startswith(("postgres://", "postgresql://"))


def default_target(fallback: str = "triage.db") -> str:
    """DATABASE_URL wins (deployed); otherwise the local SQLite file."""
    return os.environ.get("DATABASE_URL") or fallback


class Row(dict):
    """A row readable by column name (row["x"]) and by position (row[0]), like sqlite3.Row."""

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def _sqlite_row(cursor, values):
    return Row(zip((d[0] for d in cursor.description), values))


def _pg_row(cursor):
    names = [d.name for d in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))


class Database:
    """A connection with a dialect. execute() returns a cursor; rows are Row objects."""

    def __init__(self, target: str):
        self.target = target
        self.postgres = is_postgres(target)
        if self.postgres:
            import psycopg
            # prepare_threshold=None: no server-side prepared statements, so a connection
            # pooler in transaction mode (e.g. Neon's "-pooler" host) works too.
            self.conn = psycopg.connect(target, row_factory=_pg_row, connect_timeout=15, prepare_threshold=None)
        else:
            self.conn = sqlite3.connect(target, timeout=10, check_same_thread=False)
            self.conn.row_factory = _sqlite_row

    def sql(self, q: str) -> str:
        if not self.postgres:
            return q
        return q.replace("%", "%%").replace("?", "%s").replace(AUTO_ID_SQLITE, AUTO_ID_PG)

    def execute(self, q: str, args: Iterable[Any] = ()):
        return self.conn.execute(self.sql(q), tuple(args))

    def script(self, q: str) -> None:
        """Several ;-separated statements without parameters (schemas)."""
        if self.postgres:
            for stmt in (s.strip() for s in q.split(";")):
                if stmt:
                    self.conn.execute(self.sql(stmt))
            self.conn.commit()
        else:
            self.conn.executescript(q)

    def columns(self, table: str) -> set[str]:
        if self.postgres:
            rows = self.execute("SELECT column_name FROM information_schema.columns WHERE table_name = ?", (table,))
            return {r["column_name"] for r in rows}
        return {r["name"] for r in self.conn.execute(f"PRAGMA table_info({table})")}

    def commit(self) -> None:
        self.conn.commit()

    def rollback(self) -> None:
        self.conn.rollback()

    def close(self) -> None:
        self.conn.close()


def connect(target: str) -> Database:
    return Database(target)
